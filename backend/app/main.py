
import json
import os
from pathlib import Path

from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware

from .schemas import PredictRequest
from .model_service import load_bundle, predict_one


# --------------------------------------------------
# Application configuration
# --------------------------------------------------

app = FastAPI(
    title="NEWSCHECK API",
    version="1.0.0",
    description=(
        "Academic NLP text-classification prototype; "
        "not an independent fact-checker."
    ),
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=[
        os.getenv("FRONTEND_ORIGIN", "http://localhost:5173")
    ],
    allow_credentials=False,
    allow_methods=["GET", "POST"],
    allow_headers=["Content-Type"],
)


# --------------------------------------------------
# Project paths
# backend/app/main.py -> project root
# --------------------------------------------------

PROJECT_ROOT = Path(__file__).resolve().parents[2]
METRICS_FILE = PROJECT_ROOT / "outputs" / "classical_metrics.json"


# --------------------------------------------------
# Health endpoint
# --------------------------------------------------

@app.get("/health")
def health():
    trained = load_bundle() is not None

    return {
        "status": "ready" if trained else "models_not_trained",
        "models_trained": trained,
    }



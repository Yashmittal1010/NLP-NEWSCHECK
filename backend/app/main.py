# --------------------------------------------------
# News text prediction
# --------------------------------------------------

@app.post("/predict")
def predict(request: PredictRequest):
    try:
        return predict_one(request.text, request.model)

    except RuntimeError as exc:
        raise HTTPException(
            status_code=503,
            detail=str(exc),
        ) from exc

    except Exception as exc:
        raise HTTPException(
            status_code=500,
            detail=f"Prediction failed: {type(exc).__name__}",
        ) from exc


# --------------------------------------------------
# Model evaluation metrics
# --------------------------------------------------

@app.get("/metrics")
def get_metrics():
    """
    Return the saved evaluation metrics generated by
    backend/train_classical.py.
    """

    if not METRICS_FILE.is_file():
        raise HTTPException(
            status_code=404,
            detail=(
                "Evaluation metrics not found. "
                "Train the classical models first."
            ),
        )

    try:
        with METRICS_FILE.open("r", encoding="utf-8") as file:
            metrics = json.load(file)

        if not isinstance(metrics, dict) or not isinstance(
            metrics.get("models"), dict
        ):
            raise ValueError("Unexpected metrics file structure.")

        return metrics

    except (json.JSONDecodeError, ValueError) as exc:
        raise HTTPException(
            status_code=500,
            detail="The evaluation metrics file contains invalid data.",
        ) from exc

    except OSError as exc:
        raise HTTPException(
            status_code=500,
            detail="Could not read the evaluation metrics file.",
        ) from exc
